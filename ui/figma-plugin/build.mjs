// Embeds tokens/horizon.tokens.json into src/code.js -> code.js (Figma loads a single file).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(root, 'tokens/horizon.tokens.json'), 'utf8'));
const src = readFileSync(join(root, 'src/code.js'), 'utf8');
if (!src.includes('/*__TOKENS__*/null')) throw new Error('token placeholder missing in src/code.js');
const banner = '// GENERATED by build.mjs from src/code.js + tokens/horizon.tokens.json. Do not edit.\n';
writeFileSync(join(root, 'code.js'), banner + src.replace('/*__TOKENS__*/null', JSON.stringify(tokens)));
console.log('built code.js');
